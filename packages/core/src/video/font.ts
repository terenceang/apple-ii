const CELL_WIDTH = 7;
const CELL_HEIGHT = 8;

function parseGlyph(rows: string[]): Uint8Array {
  const packed = new Uint8Array(CELL_HEIGHT);
  for (let row = 0; row < 7; row++) {
    const line = rows[row] ?? ".....";
    let bits = 0;
    for (let col = 0; col < 5; col++) {
      if (line[col] === "#") bits |= 1 << (5 - col); // 1px left margin
    }
    packed[row] = bits;
  }
  packed[7] = 0; // blank spacer row
  return packed;
}

const glyphCache = new Map<number, Uint8Array>();
const BLANK_GLYPH = parseGlyph(GLYPHS[" "]!);

for (const [ch, rows] of Object.entries(GLYPHS)) {
  const glyph = parseGlyph(rows);
  glyphCache.set(ch.charCodeAt(0), glyph);
  const upper = ch.toUpperCase();
  const lower = ch.toLowerCase();
  if (upper !== ch) glyphCache.set(upper.charCodeAt(0), glyph);
  if (lower !== ch && !glyphCache.has(lower.charCodeAt(0))) glyphCache.set(lower.charCodeAt(0), glyph);
}

/** Returns 8 row-bytes (bits 1-5 = pixels, MSB-first within that range) for the given ASCII code. */
export function getGlyph(asciiCode: number): Uint8Array {
  return glyphCache.get(asciiCode & 0x7f) ?? BLANK_GLYPH;
}

